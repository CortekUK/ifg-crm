// Rebuild the three "Brochure:" templates out of real editor blocks.
//
// They arrived as pasted HTML, so they lived in a single `html` block: an
// unreadable textarea that renders a warning banner, can't be edited with the
// normal controls, and — as happened to the Gap Year one — quietly accepts
// stray keystrokes into the middle of the markup ("View the broc]]hure").
//
// Structure mirrors the other 23 templates: text blocks, a button block, and
// nothing else. The sign-off is deliberately dropped — the global footer
// already renders the recruiter signature, so keeping "Best, {{deal_owner_name}}"
// in the body printed it twice.
//
//   node scripts/rebuild-brochure-templates.mjs          # preview only
//   node scripts/rebuild-brochure-templates.mjs --write  # apply
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import crypto from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { createRequire } from 'node:module'
import { createClient } from '@supabase/supabase-js'

const require = createRequire(import.meta.url)

for (const line of fs.readFileSync('.env', 'utf8').split('\n')) {
  const m = line.match(/^([A-Z_0-9]+)=(.*)$/)
  if (m) process.env[m[1]] = m[2].trim()
}

const WRITE = process.argv.includes('--write')
const sb = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY)

// body_html is what the send path actually emails, so it has to be
// regenerated by the real renderer — not by a second copy of the markup in
// this script. Same compile-and-require trick migrate-template-branding.mjs
// uses.
const outDir = fs.mkdtempSync(path.join(os.tmpdir(), 'ifg-brochure-'))
execFileSync(
  'npx',
  ['tsc', 'lib/templates/render-html.ts',
   '--outDir', outDir, '--rootDir', 'lib/templates',
   '--module', 'commonjs', '--target', 'es2020',
   '--moduleResolution', 'node', '--esModuleInterop', '--skipLibCheck'],
  { stdio: 'inherit' },
)
const { renderBlocksToHTML } = require(path.join(outDir, 'render-html.js'))

const text = (html, extra = {}) => ({
  id: crypto.randomUUID(),
  type: 'text',
  content: { html, alignment: 'left', fontSize: 'normal', paddingTop: 10, paddingBottom: 10, ...extra },
})

const button = (label, url) => ({
  id: crypto.randomUUID(),
  type: 'button',
  content: {
    text: label,
    url,
    backgroundColor: '#BE1623', // IFG red, as the pasted markup used
    textColor: '#ffffff',
    borderRadius: 999,          // pill, matching the original
    width: 'auto',
    alignment: 'center',
    paddingTop: 20,
    paddingBottom: 20,
    paddingX: 32,
    paddingY: 14,
  },
})

const { data: templates, error } = await sb
  .from('email_templates')
  .select('id, name, body_html, body_json, theme')
  .like('name', 'Brochure:%')

if (error) { console.error(error.message); process.exit(1) }

let changed = 0
for (const t of templates) {
  const source = t.body_json?.[0]?.content?.code || t.body_html || ''

  // The brochure link is the one thing that must survive verbatim.
  const url = source.match(/href="([^"]*\/b\/[^"]*)"/)?.[1]
  if (!url) {
    console.error(`ABORT ${t.name} — no brochure link found, refusing to rebuild`)
    process.exit(1)
  }

  // "Brochure: Gap Year Brochure" -> "Gap Year Brochure"
  const label = t.name.replace(/^Brochure:\s*/, '').trim()

  const blocks = [
    text('<p>Hi {{first_name}},</p>'),
    text(`<p>Here's the ${label} — everything you need in one place:</p>`),
    button('View the brochure →', url),
    text('<p>Any questions at all, just reply to this email.</p>'),
  ]

  console.log(`rebuild  ${t.name}`)
  console.log(`         ${blocks.length} blocks: ${blocks.map((b) => b.type).join(', ')}`)
  console.log(`         link: ${url}`)
  if (source.includes(']]')) console.log(`         (also clears the "]]" typo in the old markup)`)
  changed++

  const html = renderBlocksToHTML(blocks, t.theme ?? null)

  for (const marker of ['<!--IFG_GLOBAL_HEADER-->', '<!--IFG_GLOBAL_FOOTER-->', '<!--IFG_GLOBAL_LEGAL-->']) {
    if (!html.includes(marker)) {
      console.error(`ABORT ${t.name} — rendered HTML is missing ${marker}`)
      process.exit(1)
    }
  }
  if (!html.includes(url)) {
    console.error(`ABORT ${t.name} — brochure link missing from rendered HTML`)
    process.exit(1)
  }
  if (html.includes(']]')) {
    console.error(`ABORT ${t.name} — rendered HTML still contains "]]"`)
    process.exit(1)
  }

  console.log(`         rendered ${html.length} bytes, markers + link verified`)

  if (WRITE) {
    const { error: upErr } = await sb
      .from('email_templates')
      .update({ body_json: blocks, body_html: html, updated_at: new Date().toISOString() })
      .eq('id', t.id)
    if (upErr) { console.error(`  failed: ${upErr.message}`); process.exit(1) }
  }
}

console.log(`\n${changed} template(s) ${WRITE ? 'updated' : 'would change'}.`)
if (!WRITE && changed) console.log('Re-run with --write to apply.')
